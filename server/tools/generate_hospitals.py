"""Generates the hospitals seed migration from OpenStreetMap (Overpass API).

Run from the repository root:
    python server/tools/generate_hospitals.py

Writes server/src/main/resources/db/migration/V3__hospitals.sql and prints a
review report (possible clinics and duplicates) to stdout. The server never
calls Overpass itself; regenerate and add a NEW migration to refresh the data.

Hospital data (c) OpenStreetMap contributors, ODbL.
"""

import json
import math
import re
import sys
import urllib.parse
import urllib.request
from datetime import date
from pathlib import Path

OVERPASS_URL = "https://overpass-api.de/api/interpreter"
QUERY = """
[out:json][timeout:120];
area["ISO3166-1"="LB"][admin_level=2]->.lb;
nwr["amenity"="hospital"](area.lb);
out center tags;
"""

OUTPUT = Path(__file__).resolve().parents[1] / "src/main/resources/db/migration/V3__hospitals.sql"

ARABIC = re.compile(r"[؀-ۿ]")
CLINIC_WORDS = re.compile(
    r"clinic|cent(er|re)|dispensary|medical|polyclinic|dental|laborator|مستوصف|مركز|عيادة",
    re.IGNORECASE,
)
DUPLICATE_DISTANCE_M = 300


def fetch():
    data = urllib.parse.urlencode({"data": QUERY}).encode()
    request = urllib.request.Request(
        OVERPASS_URL, data=data, headers={"User-Agent": "BloodDonor-seed-generator/1.0"}
    )
    with urllib.request.urlopen(request, timeout=180) as response:
        return json.load(response)["elements"]


def clean(text):
    return " ".join(text.split()) if text else None


def to_hospital(element):
    tags = element.get("tags", {})
    name_en = clean(tags.get("name:en"))
    name = clean(tags.get("name"))
    display = name_en or name
    if not display:
        return None
    name_ar = clean(tags.get("name:ar"))
    if not name_ar and name and ARABIC.search(name):
        name_ar = name
    if element["type"] == "node":
        lat, lon = element["lat"], element["lon"]
    else:
        center = element.get("center")
        if not center:
            return None
        lat, lon = center["lat"], center["lon"]
    return {
        "osm_id": f"{element['type']}/{element['id']}",
        "name": display,
        "name_ar": name_ar if name_ar != display else None,
        "lat": round(lat, 6),
        "lon": round(lon, 6),
    }


def distance_m(a, b):
    lat1, lon1, lat2, lon2 = map(math.radians, (a["lat"], a["lon"], b["lat"], b["lon"]))
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2
    return 2 * 6371000 * math.asin(math.sqrt(h))


def normalize(name):
    name = name.lower()
    name = re.sub(r"\b(hospital|medical|center|centre|university|general|the)\b", " ", name)
    return re.sub(r"[^a-z0-9؀-ۿ]+", "", name)


def sql_text(value):
    return "NULL" if value is None else "'" + value.replace("'", "''") + "'"


def write_sql(hospitals):
    rows = ",\n".join(
        f"    ({sql_text(h['osm_id'])}, {sql_text(h['name'])}, {sql_text(h['name_ar'])}, {h['lat']}, {h['lon']})"
        for h in hospitals
    )
    OUTPUT.write_text(
        f"""-- Hospitals in Lebanon, generated by server/tools/generate_hospitals.py on {date.today()}.
-- Source: OpenStreetMap (amenity=hospital), Hospital data (c) OpenStreetMap contributors, ODbL.
-- Do not edit by hand; to refresh, regenerate into a NEW migration.

CREATE TABLE hospitals (
    id        integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name      text NOT NULL,
    name_ar   text,
    area_id   integer NOT NULL REFERENCES areas (id),
    location  geography(Point, 4326) NOT NULL,
    -- e.g. node/123 or way/456 (node and way ids can collide, so the type is kept)
    osm_id    text NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true
);

CREATE INDEX hospitals_area_idx ON hospitals (area_id) WHERE is_active;

-- area_id is the nearest area (by distance) to each hospital.
INSERT INTO hospitals (osm_id, name, name_ar, area_id, location)
SELECT seed.osm_id, seed.name, seed.name_ar,
       (SELECT a.id FROM areas a
        ORDER BY ST_Distance(a.location, ST_SetSRID(ST_MakePoint(seed.lon, seed.lat), 4326)::geography)
        LIMIT 1),
       ST_SetSRID(ST_MakePoint(seed.lon, seed.lat), 4326)::geography
FROM (VALUES
{rows}
) AS seed(osm_id, name, name_ar, lat, lon);
""",
        encoding="utf-8",
        newline="\n",
    )


def main():
    elements = fetch()
    hospitals, skipped = [], 0
    for element in elements:
        hospital = to_hospital(element)
        if hospital:
            hospitals.append(hospital)
        else:
            skipped += 1
    hospitals.sort(key=lambda h: (h["name"].lower(), h["osm_id"]))
    write_sql(hospitals)

    out = sys.stdout
    out.write(f"Fetched {len(elements)} OSM elements, {len(hospitals)} hospitals written, {skipped} skipped (no name).\n")
    out.write(f"Wrote {OUTPUT}\n\n")

    out.write("== Names that look like clinics / centers ==\n")
    for h in hospitals:
        if CLINIC_WORDS.search(h["name"]):
            out.write(f"  {h['osm_id']:<18} {h['name']}\n")

    out.write(f"\n== Possible duplicates (same normalized name, or within {DUPLICATE_DISTANCE_M} m) ==\n")
    for i, a in enumerate(hospitals):
        for b in hospitals[i + 1:]:
            d = distance_m(a, b)
            if d <= DUPLICATE_DISTANCE_M or normalize(a["name"]) == normalize(b["name"]):
                out.write(f"  {a['osm_id']:<18} {a['name']}\n  {b['osm_id']:<18} {b['name']}   ({d:.0f} m apart)\n\n")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
